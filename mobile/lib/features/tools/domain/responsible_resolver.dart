/// Чистая логика выбора ответственного по умолчанию для инструмента,
/// добавляемого в проект.
///
/// NEWFIX TЗ-2 §8.3: при добавлении инструмента в проект «ответственный
/// сотрудник» по умолчанию = бригадир проекта. Пользователь всё ещё может
/// изменить выбор вручную — это только pre-fill, не lock.
///
/// Вынесено в чистую функцию, чтобы юнит-тесты не требовали поднимать UI и
/// весь Riverpod-граф (teamController зависит от dio/socket/etc.).
library;

import '../../projects/domain/membership.dart';

/// Возвращает `userId` первого бригадира (foreman) из списка members.
/// Если бригадира в проекте нет — возвращает `null` (вызывающий код должен
/// быть готов к этому и НЕ падать).
///
/// Если в проекте несколько бригадиров (теоретически возможно при ручном
/// переназначении), берём первого по порядку поступления — порядок задаётся
/// бекендом (`MembersService.list` сортирует по `createdAt`).
String? resolveProjectForemanId(Iterable<Membership> members) {
  for (final m in members) {
    if (m.role == MembershipRole.foreman) {
      return m.userId;
    }
  }
  return null;
}
